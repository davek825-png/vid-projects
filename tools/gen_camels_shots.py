"""Generate the ows-camels shot wrappers + timelines for all three visual styles.

The beats are written once (remotion/src/shots/ows-camels/_beats.tsx, on lib/tristyle.tsx) and
their spans live in _spans.ts. This writes, from those spans:
  remotion/src/shots/ows-camels/Cm<Beat>.tsx          default (documentary)
  remotion/src/shots/ows-camels-cutout/Cut<Beat>.tsx  cutout (paper, stop-motion)
  remotion/src/shots/ows-camels-clay/Clay<Beat>.tsx   claymation
  videos/ows-camels/work/timeline{,-cutout,-clay}.json
compositionConfig durations must be literals (gen-registry parses them with a regex), which is
why these wrappers are generated rather than hand-written. Re-run after any retime in _spans.ts,
then `cd remotion && npm run gen`.

Usage (repo root): python tools/gen_camels_shots.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHOTS = ROOT / "remotion" / "src" / "shots"
SPANS_TS = SHOTS / "ows-camels" / "_spans.ts"
PROJECT = "videos/ows-camels"

STYLES = [
    # (style, folder, id prefix, timeline file, preview file)
    ("default", "ows-camels", "Cm", "timeline.json", "ows-camels-preview.mp4"),
    ("cutout", "ows-camels-cutout", "Cut", "timeline-cutout.json", "ows-camels-preview-cutout.mp4"),
    ("claymation", "ows-camels-clay", "Clay", "timeline-clay.json", "ows-camels-preview-clay.mp4"),
]


def load_spans():
    spans = re.findall(r"^\s*(\w+):\s*\[([\d.]+),\s*([\d.]+)\]", SPANS_TS.read_text(encoding="utf-8"), re.M)
    out = [(n, float(a), float(b)) for n, a, b in spans]
    for (n0, _, e0), (n1, s1, _) in zip(out, out[1:]):  # narration-only: beats must tile, no gaps
        assert abs(e0 - s1) < 1e-6, f"gap/overlap between {n0} and {n1}"
    return out


def main():
    spans = load_spans()
    for style, folder, prefix, tl_name, preview in STYLES:
        d = SHOTS / folder
        d.mkdir(parents=True, exist_ok=True)
        rel = "." if folder == "ows-camels" else "../ows-camels"
        for name, s, e in spans:
            sid = f"{prefix}{name}"
            (d / f"{sid}.tsx").write_text(
                f"// GENERATED by tools/gen_camels_shots.py ({style}). Edit the beat in ows-camels/_beats.tsx.\n"
                f"import React from 'react';\n"
                f"import {{ StyleProvider }} from '../../lib/tristyle';\n"
                f"import {{ {name} }} from '{rel}/_beats';\n\n"
                f"export const compositionConfig = {{ id: '{sid}', durationInSeconds: {round(e - s, 3)}, fps: 30, width: 1920, height: 1080 }};\n\n"
                f"const {sid}: React.FC = () => <StyleProvider value=\"{style}\"><{name} /></StyleProvider>;\n"
                f"export default {sid};\n",
                encoding="utf-8",
            )
        tl = {
            "note": "Narration-only video: the master picture is blank, so cutaways tile 0..end with no gaps. "
                    f"GENERATED by tools/gen_camels_shots.py from _spans.ts ({style} style).",
            "style": style,
            "master": f"{PROJECT}/output/master-natural-slow-h264.mp4",
            "master_fps": 30,
            "remotion_out": "remotion/out",
            "shots": [{"id": f"{prefix}{n}", "type": "cutaway", "master_in_s": s, "master_out_s": e, "cue": n} for n, s, e in spans],
            "preview": {"end_s": spans[-1][2], "out": f"{PROJECT}/output/{preview}", "width": 1920, "height": 1080, "fps": 30},
        }
        (ROOT / PROJECT / "work" / tl_name).write_text(json.dumps(tl, indent=2), encoding="utf-8")
        print(f"{style}: {len(spans)} shots -> {folder}/ + work/{tl_name}")


if __name__ == "__main__":
    main()
