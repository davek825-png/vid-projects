#!/usr/bin/env python3
"""
gen_shots.py — write a video's shot wrappers + timeline.json from ONE span table.

Beats are written once as named React components in remotion/src/shots/<folder>/_beats.tsx; their
master spans live in _spans.ts (`export const SPANS = { Name: [in_s, out_s], ... }`, in order, tiling
with no gaps for narration-only videos). This writes <folder>/<Prefix><Name>.tsx for each span
(compositionConfig durations must be literals: gen-registry parses them with a regex) and the
project's work/timeline.json. Re-run after any retime, then `cd remotion && npm run gen`.

Usage (repo root):
  python tools/gen_shots.py <folder> <Prefix> <videos/project> [--master <path>] [--end <s>]
  e.g. python tools/gen_shots.py ows-hickok Hk videos/ows-hickok
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHOTS = ROOT / "remotion" / "src" / "shots"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("folder"); ap.add_argument("prefix"); ap.add_argument("project")
    ap.add_argument("--master", default=None)
    ap.add_argument("--end", type=float, default=None, help="master duration (defaults to the last span's end)")
    a = ap.parse_args()
    d = SHOTS / a.folder
    src = (d / "_spans.ts").read_text(encoding="utf-8")
    spans = [(n, float(s), float(e)) for n, s, e in re.findall(r"^\s*(\w+):\s*\[([\d.]+),\s*([\d.]+)\]", src, re.M)]
    assert spans, "no spans found"
    for (n0, s0, e0), (n1, s1, _) in zip(spans, spans[1:]):
        assert abs(e0 - s1) < 1e-6, f"gap/overlap between {n0} and {n1}"
        assert e0 > s0, f"{n0} has no duration"
    for name, s, e in spans:
        sid = f"{a.prefix}{name}"
        (d / f"{sid}.tsx").write_text(
            f"// GENERATED by tools/gen_shots.py. Edit the beat in {a.folder}/_beats.tsx, timing in _spans.ts.\n"
            f"import React from 'react';\nimport {{ {name} }} from './_beats';\n\n"
            f"export const compositionConfig = {{ id: '{sid}', durationInSeconds: {round(e - s, 3)}, fps: 30, width: 1920, height: 1080 }};\n\n"
            f"const {sid}: React.FC = () => <{name} />;\nexport default {sid};\n", encoding="utf-8")
    proj = a.project.rstrip("/")
    name = Path(proj).name
    tl = {
        "note": "Narration-only video: the master picture is blank, so cutaways tile 0..end with no gaps. GENERATED by tools/gen_shots.py from _spans.ts.",
        "style": "default",
        "master": a.master or f"{proj}/output/master-natural-slow-h264.mp4",
        "master_fps": 30, "remotion_out": "remotion/out",
        "shots": [{"id": f"{a.prefix}{n}", "type": "cutaway", "master_in_s": s, "master_out_s": e, "cue": n} for n, s, e in spans],
        "preview": {"end_s": a.end or spans[-1][2], "out": f"{proj}/output/{name}-preview.mp4", "width": 1920, "height": 1080, "fps": 30},
    }
    (ROOT / proj / "work" / "timeline.json").write_text(json.dumps(tl, indent=2), encoding="utf-8")
    print(f"{len(spans)} shots -> shots/{a.folder}/{a.prefix}*.tsx + {proj}/work/timeline.json")


if __name__ == "__main__":
    main()
